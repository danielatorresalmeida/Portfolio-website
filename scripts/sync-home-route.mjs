import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT_DIR = path.resolve(__dirname, "..");
const SOURCE_FILE = path.join(ROOT_DIR, "index.html");
const TARGET_DIR = path.join(ROOT_DIR, "home");
const TARGET_FILE = path.join(TARGET_DIR, "index.html");
const GENERATED_NOTICE = "<!-- Generated by scripts/sync-home-route.mjs. Edit the root index.html instead. -->";
const LOCAL_URL_ATTRIBUTES = /\b(href|src|data-href|data-cv-en|data-cv-pt)="([^"]+)"/g;

function isRelativeLocalUrl(value) {
  if (!value || value.startsWith("#") || value.startsWith("/")) return false;
  return !/^[a-z][a-z0-9+.-]*:/i.test(value);
}

export function createHomeRouteHtml(source) {
  const withAdjustedPaths = source.replace(
    LOCAL_URL_ATTRIBUTES,
    (match, attribute, value) => {
      if (!isRelativeLocalUrl(value)) return match;
      const normalized = value.startsWith("./") ? value.slice(2) : value;
      return `${attribute}="../${normalized}"`;
    }
  );

  return withAdjustedPaths.replace(
    /(<html\b[^>]*>)/i,
    `${GENERATED_NOTICE}\n$1`
  );
}

export function syncHomeRoute({ checkOnly = false } = {}) {
  const source = fs.readFileSync(SOURCE_FILE, "utf8");
  const expected = createHomeRouteHtml(source);
  const current = fs.existsSync(TARGET_FILE)
    ? fs.readFileSync(TARGET_FILE, "utf8")
    : "";

  if (checkOnly) {
    if (current !== expected) {
      throw new Error("home/index.html is out of date. Run npm run sync:home.");
    }
    return { changed: false, target: TARGET_FILE };
  }

  fs.mkdirSync(TARGET_DIR, { recursive: true });
  if (current === expected) return { changed: false, target: TARGET_FILE };
  fs.writeFileSync(TARGET_FILE, expected, "utf8");
  return { changed: true, target: TARGET_FILE };
}

const checkOnly = process.argv.includes("--check");

try {
  const result = syncHomeRoute({ checkOnly });
  const action = checkOnly
    ? "Home route is synchronized"
    : result.changed
      ? "Generated home/index.html"
      : "Home route already synchronized";
  console.log(action);
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
